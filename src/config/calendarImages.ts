import type { ImageSourcePropType } from 'react-native';

export type CalendarSeasonKey = 'spring' | 'summer' | 'autom' | 'winter';

export interface CalendarImageSource {
  uri: string;
  fallback: ImageSourcePropType;
}

const CALENDAR_ASSET_BASE_URL = (
  process.env.EXPO_PUBLIC_CALENDAR_ASSET_BASE_URL || 'https://assets.numelyra.online'
).replace(/\/+$/, '');

const FALLBACK_IMAGES: Record<CalendarSeasonKey, ImageSourcePropType> = {
  spring: require('../../image/spring/Artisan_blending_tea_with_flame_20260919105940.jpeg'),
  summer: require('../../image/summer/Artisan_molding_rice_dough_figures_20260919105925.jpeg'),
  autom: require('../../image/autom/Artisan_assembling_rotating_shad…_20260919105944.jpeg'),
  winter: require('../../image/winter/Artisan_shaping_clay_vase_20260919110225.jpeg')
};

function remoteImage(season: CalendarSeasonKey, filename: string): CalendarImageSource {
  return {
    uri: `${CALENDAR_ASSET_BASE_URL}/${season}/${encodeURIComponent(filename)}`,
    fallback: FALLBACK_IMAGES[season]
  };
}

